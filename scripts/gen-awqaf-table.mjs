// Turns docs/awqaf-abu-dhabi.txt (Awqaf's official monthly tables) into src/data/awqaf-abu-dhabi.ts.
// Add new months to the txt (from awqaf.gov.ae → Prayer Times → Download), then: node scripts/gen-awqaf-table.mjs
import fs from "fs";
const rows = fs.readFileSync("docs/awqaf-abu-dhabi.txt", "utf8").split("\n").filter((l) => /^\d{4}-\d\d-\d\d /.test(l));
const body = rows.map((l) => `  "${l.slice(0, 10)}": "${l.slice(11).trim()}",`).join("\n");
fs.writeFileSync(
  "src/data/awqaf-abu-dhabi.ts",
  `// Generated by scripts/gen-awqaf-table.mjs from docs/awqaf-abu-dhabi.txt - do not edit.\n` +
    `// Official UAE Awqaf prayer times for Abu Dhabi: "fajr shurooq dhuhr asr maghrib isha" (24h, UTC+4).\n` +
    `export const AWQAF_ABU_DHABI: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${rows.length} days, ${rows[0].slice(0, 10)} to ${rows.at(-1).slice(0, 10)}`);
